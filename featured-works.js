// Global variables
let currentWorkIndex = 0;
let currentImageIndex = 0;
let isModalOpen = false;

// DOM elements
const worksTrack = document.getElementById('worksTrack');
const prevBtn = document.getElementById('prevBtn');
const nextBtn = document.getElementById('nextBtn');
const modalOverlay = document.getElementById('modalOverlay');
const modalClose = document.getElementById('modalClose');
const modalImage = document.getElementById('modalImage');
const modalTitle = document.getElementById('modalTitle');
const modalDescription = document.getElementById('modalDescription');
const modalLink = document.getElementById('modalLink');
const prevImage = document.getElementById('prevImage');
const nextImage = document.getElementById('nextImage');
const prevWork = document.getElementById('prevWork');
const nextWork = document.getElementById('nextWork');

// Initialize the carousel
function initializeCarousel() {
    renderWorks();
    updateCarouselPosition();
    updateNavigationButtons();
}

// Render works in the carousel
function renderWorks() {
    worksTrack.innerHTML = '';
    
    featuredWorks.forEach((work, index) => {
        const workItem = document.createElement('div');
        workItem.className = 'work-item';
        workItem.innerHTML = `
            <img src="${work.images[0]}" alt="${work.title}">
            <div class="work-overlay">
                <h4>${work.title}</h4>
            </div>
        `;
        
        workItem.addEventListener('click', () => openModal(index));
        worksTrack.appendChild(workItem);
    });
}

// Update carousel position
function updateCarouselPosition() {
    const itemWidth = 320; // 300px width + 20px gap
    const translateX = -currentWorkIndex * itemWidth;
    worksTrack.style.transform = `translateX(${translateX}px)`;
}

// Update navigation button states
function updateNavigationButtons() {
    prevBtn.disabled = currentWorkIndex === 0;
    nextBtn.disabled = currentWorkIndex >= featuredWorks.length - 3; // Show 3 items at once
    
    if (prevBtn.disabled) {
        prevBtn.style.opacity = '0.5';
        prevBtn.style.cursor = 'not-allowed';
    } else {
        prevBtn.style.opacity = '1';
        prevBtn.style.cursor = 'pointer';
    }
    
    if (nextBtn.disabled) {
        nextBtn.style.opacity = '0.5';
        nextBtn.style.cursor = 'not-allowed';
    } else {
        nextBtn.style.opacity = '1';
        nextBtn.style.cursor = 'pointer';
    }
}

// Open modal with work details
function openModal(workIndex) {
    currentWorkIndex = workIndex;
    currentImageIndex = 0;
    isModalOpen = true;
    
    const work = featuredWorks[workIndex];
    
    // Update modal content
    modalImage.src = work.images[currentImageIndex];
    modalTitle.innerHTML = work.title;
    modalDescription.innerHTML = work.description;
    modalLink.href = work.link;
    modalLink.textContent = work.linkText;
    
    // Show/hide image navigation based on number of images
    if (work.images.length > 1) {
        prevImage.style.display = 'flex';
        nextImage.style.display = 'flex';
    } else {
        prevImage.style.display = 'none';
        nextImage.style.display = 'none';
    }
    
    // Update modal navigation buttons
    updateModalNavigation();
    
    // Show modal
    modalOverlay.classList.add('active');
    document.body.style.overflow = 'hidden';
}

// Close modal
function closeModal() {
    isModalOpen = false;
    modalOverlay.classList.remove('active');
    document.body.style.overflow = 'auto';
}

// Update modal navigation buttons
function updateModalNavigation() {
    const work = featuredWorks[currentWorkIndex];
    
    // Image navigation
    prevImage.disabled = currentImageIndex === 0;
    nextImage.disabled = currentImageIndex === work.images.length - 1;
    
    // Work navigation
    prevWork.disabled = currentWorkIndex === 0;
    nextWork.disabled = currentWorkIndex === featuredWorks.length - 1;
}

// Navigate to previous work
function navigateToPrevWork() {
    if (currentWorkIndex > 0) {
        currentWorkIndex--;
        openModal(currentWorkIndex);
    }
}

// Navigate to next work
function navigateToNextWork() {
    if (currentWorkIndex < featuredWorks.length - 1) {
        currentWorkIndex++;
        openModal(currentWorkIndex);
    }
}

// Navigate to previous image
function navigateToPrevImage() {
    const work = featuredWorks[currentWorkIndex];
    if (currentImageIndex > 0) {
        currentImageIndex--;
        modalImage.src = work.images[currentImageIndex];
        updateModalNavigation();
    }
}

// Navigate to next image
function navigateToNextImage() {
    const work = featuredWorks[currentWorkIndex];
    if (currentImageIndex < work.images.length - 1) {
        currentImageIndex++;
        modalImage.src = work.images[currentImageIndex];
        updateModalNavigation();
    }
}

// Event listeners
document.addEventListener('DOMContentLoaded', function() {
    // Initialize carousel
    initializeCarousel();
    
    // Carousel navigation
    prevBtn.addEventListener('click', () => {
        if (currentWorkIndex > 0) {
            currentWorkIndex--;
            updateCarouselPosition();
            updateNavigationButtons();
        }
    });
    
    nextBtn.addEventListener('click', () => {
        if (currentWorkIndex < featuredWorks.length - 3) {
            currentWorkIndex++;
            updateCarouselPosition();
            updateNavigationButtons();
        }
    });
    
    // Modal controls
    modalClose.addEventListener('click', closeModal);
    
    modalOverlay.addEventListener('click', (e) => {
        if (e.target === modalOverlay) {
            closeModal();
        }
    });
    
    // Image navigation
    prevImage.addEventListener('click', navigateToPrevImage);
    nextImage.addEventListener('click', navigateToNextImage);
    
    // Work navigation
    prevWork.addEventListener('click', navigateToPrevWork);
    nextWork.addEventListener('click', navigateToNextWork);
    
    // Keyboard navigation
    document.addEventListener('keydown', (e) => {
        if (!isModalOpen) return;
        
        switch(e.key) {
            case 'Escape':
                closeModal();
                break;
            case 'ArrowLeft':
                if (currentImageIndex > 0) {
                    navigateToPrevImage();
                } else {
                    navigateToPrevWork();
                }
                break;
            case 'ArrowRight':
                if (currentImageIndex < featuredWorks[currentWorkIndex].images.length - 1) {
                    navigateToNextImage();
                } else {
                    navigateToNextWork();
                }
                break;
        }
    });
    
    // Touch/swipe support for mobile
    let startX = 0;
    let startY = 0;
    
    modalOverlay.addEventListener('touchstart', (e) => {
        startX = e.touches[0].clientX;
        startY = e.touches[0].clientY;
    });
    
    modalOverlay.addEventListener('touchend', (e) => {
        if (!isModalOpen) return;
        
        const endX = e.changedTouches[0].clientX;
        const endY = e.changedTouches[0].clientY;
        const diffX = startX - endX;
        const diffY = startY - endY;
        
        // Only handle horizontal swipes
        if (Math.abs(diffX) > Math.abs(diffY) && Math.abs(diffX) > 50) {
            if (diffX > 0) {
                // Swipe left - next image/work
                if (currentImageIndex < featuredWorks[currentWorkIndex].images.length - 1) {
                    navigateToNextImage();
                } else {
                    navigateToNextWork();
                }
            } else {
                // Swipe right - previous image/work
                if (currentImageIndex > 0) {
                    navigateToPrevImage();
                } else {
                    navigateToPrevWork();
                }
            }
        }
    });
});

// Handle window resize
window.addEventListener('resize', () => {
    if (isModalOpen) {
        updateModalNavigation();
    }
});
