// Function to update image navigation buttons state
function updateImageNavButtons() {
    const work = workData[workOrder[currentWorkIndex]];
    const prevBtn = document.querySelector('.prev-btn');
    const nextBtn = document.querySelector('.next-btn');
    
    if (prevBtn && nextBtn && work.images) {
        // Disable/enable based on current position
        prevBtn.disabled = currentImageIndex === 0;
        nextBtn.disabled = currentImageIndex === work.images.length - 1;
        
        // Hide if only one image
        if (work.images.length <= 1) {
            prevBtn.style.display = 'none';
            nextBtn.style.display = 'none';
        } else {
            prevBtn.style.display = 'flex';
            nextBtn.style.display = 'flex';
        }
    }
}

// Function to update work navigation buttons
function updateWorkNavButtons() {
    prevWorkBtn.disabled = currentWorkIndex === 0;
    nextWorkBtn.disabled = currentWorkIndex === workOrder.length - 1;
}

